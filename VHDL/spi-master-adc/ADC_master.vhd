library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

------------------------------------------------------------------------
-- TOP LEVEL CONTROLLER
------------------------------------------------------------------------
entity ADC_SPI_Controller is
    Port (
        ----------------------------------------------------------------
        -- System signals
        ----------------------------------------------------------------
        CLK       : in  std_logic;
   
        ----------------------------------------------------------------
        -- ADC interface
        ----------------------------------------------------------------
        MISO1     : in  std_logic;
        MISO2     : in  std_logic;
        BUSY      : in  std_logic;

        ----------------------------------------------------------------
        -- SPI control lines
        ----------------------------------------------------------------
        SCK       : out std_logic;
        CS        : out std_logic;
        CNV       : out std_logic;
        MOSI      : out std_logic;

        ----------------------------------------------------------------
        -- Output data
        ----------------------------------------------------------------
        Data1     : out std_logic_vector(23 downto 0);
        Data2     : out std_logic_vector(23 downto 0);
        DataValid : out std_logic
    );
end ADC_SPI_Controller;


------------------------------------------------------------------------
-- SPI CONFIGURATION BLOCK
------------------------------------------------------------------------
entity ADC_SPI_Config is
    Port (
        CLK          : in  std_logic; #80MHz

        ----------------------------------------------------------------
        -- Control from top FSM
        ----------------------------------------------------------------
        StartConfig  : in  std_logic;
        ConfigDone   : out std_logic;

        ----------------------------------------------------------------
        -- SPI lines
        ----------------------------------------------------------------
        SCK          : out std_logic;
        CS           : out std_logic;
        MOSI         : out std_logic
    );
end ADC_SPI_Config;


------------------------------------------------------------------------
-- ADC CONVERSION CONTROL BLOCK
------------------------------------------------------------------------
entity ADC_Conversion_Control is
    Port (
        CLK          : in  std_logic;

        ----------------------------------------------------------------
        -- ADC status
        ----------------------------------------------------------------
        BUSY         : in  std_logic;

        ----------------------------------------------------------------
        -- Control from top FSM
        ----------------------------------------------------------------
        StartConv    : in  std_logic;
        ConvDone     : out std_logic;

        ----------------------------------------------------------------
        -- ADC conversion pin
        ----------------------------------------------------------------
        CNV          : out std_logic
    );
end ADC_Conversion_Control;


------------------------------------------------------------------------
-- SPI DATA READER BLOCK
------------------------------------------------------------------------
entity ADC_SPI_Data_Read is
    Port (
        CLK          : in  std_logic;

        ----------------------------------------------------------------
        -- ADC serial data
        ----------------------------------------------------------------
        MISO1         : in  std_logic;
        MISO2         : in  std_logic;

        ----------------------------------------------------------------
        -- Control from top FSM
        ----------------------------------------------------------------
        StartRead    : in  std_logic;
        ReadDone     : out std_logic;

        ----------------------------------------------------------------
        -- SPI lines
        ----------------------------------------------------------------
        SCK          : out std_logic;
        CS           : out std_logic;

        ----------------------------------------------------------------
        -- Output data
        ----------------------------------------------------------------
        Data1        : out std_logic_vector(23 downto 0);
        Data2        : out std_logic_vector(23 downto 0)
    );
end ADC_SPI_Data_Read;